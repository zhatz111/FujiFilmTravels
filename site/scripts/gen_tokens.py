PAGE = [k for k in LIGHT if k not in ('sky-top','sky-mid','sky-bottom','sun','ridge-1','ridge-2','ridge-3')]
SKY = ['sky-top','sky-mid','sky-bottom','sun']
RIDGE = ['ridge-1','ridge-2','ridge-3']
# (duration ms, delay ms) per group. To night: the page dims first, the sky follows as the sun
# sets, the mountains darken last. To day: mirrored, the sky brightens first and the page follows.
TIMING = {
  'dark':  {'page': (1000, 0),   'sky': (1600, 300), 'ridge': (1400, 700)},
  'light': {'page': (1000, 700), 'sky': (1600, 200), 'ridge': (1400, 200)},
}
def block(vals): return '\n'.join(f'\t--{k}: {v};' for k, v in vals.items())
def timing(t):
    props, durs, dels = [], [], []
    for group, keys in (('page', PAGE), ('sky', SKY), ('ridge', RIDGE)):
        d, dl = TIMING[t][group]
        for k in keys: props.append(f'--{k}'); durs.append(f'{d}ms'); dels.append(f'{dl}ms')
    return f"\ttransition-property: {', '.join(props)};\n\ttransition-duration: {', '.join(durs)};\n\ttransition-delay: {', '.join(dels)};"
